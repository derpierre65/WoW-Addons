        cb:SetChecked(val == nil or val == true)
    end
    f:Show()
end

local frame = CreateFrame("Frame")
frame:RegisterEvent("PLAYER_ENTERING_WORLD")
frame:RegisterEvent("ADDON_LOADED")

local hasPosted = false

frame:SetScript("OnEvent", function(self, event, arg1)
    if event == "ADDON_LOADED" and arg1 == "FactorUseless" then
        FactorUselessDB = FactorUselessDB or {}
        if not FactorUselessDB.language then
            FactorUselessDB.language = GetLocale()
        end

        if not FactorUselessDB.setupDone then
            C_Timer.After(2, function()
                ShowSetupFrame()
            end)
        end
    end

    if event == "PLAYER_ENTERING_WORLD" then
        if hasPosted then
            return
        end

        hasPosted = true

        if FactorUselessDB and FactorUselessDB.postOnLogin then
            C_Timer.After(5, function()
                if IsInGuild() then
                    SendChatMessage(GetRandomFact(), "GUILD")
                end
            end)
        end
    end
end)

SLASH_FACTORUSELESS1 = "/fact"
SlashCmdList["FACTORUSELESS"] = function(msg)
    local command, rest = msg:match("^(%S+)%s*(.*)$")
    command = command and command:lower() or ""

    if command == "print" or command == "generate" then
        local category = rest ~= "" and rest:lower() or nil
        if category and not FACTS["enUS"][category] then
            local locale = GetLocale()
            local available = {}
            for key in pairs(FACTS["enUS"]) do
                available[#available + 1] = key
            end
            table.sort(available)
            if locale == "deDE" then
                print("|cff00ccffFactorUseless|r: Unbekannte Kategorie: |cffff0000" .. rest .. "|r")
            else
                print("|cff00ccffFactorUseless|r: Unknown category: |cffff0000" .. rest .. "|r")
            end
            print("  |cffffff00" .. table.concat(available, ", ") .. "|r")
            return
        end
        PostFact(category)
    elseif command == "language" or command == "lang" then
        SetLanguage(rest)
    elseif command == "setup" then
        ShowSetupFrame()
    else
        ShowHelp()
    end
end
