local function GetRandomFact(category)
    local locale = FactorUselessDB and FactorUselessDB.language or GetLocale()
    local localeFacts = FACTS[locale] or FACTS["enUS"]
    local categoryNames = CATEGORY_NAMES[locale] or CATEGORY_NAMES["enUS"]
    local allFacts = {}
    for cat, categoryFacts in pairs(localeFacts) do
        if not category or cat == category then
            local name = categoryNames[cat] or cat
            for _, fact in ipairs(categoryFacts) do
                allFacts[#allFacts + 1] = name .. ": " .. fact
            end
        end
    end

    return allFacts[math.random(#allFacts)]
end

local function GetChatTarget()
    local chatType = ChatFrame1EditBox:GetAttribute("chatType")
    local channelTarget = ChatFrame1EditBox:GetAttribute("channelTarget")

    if chatType == "CHANNEL" and channelTarget then
        return chatType, channelTarget
    end

    if chatType == "WHISPER" then
        local tellTarget = ChatFrame1EditBox:GetAttribute("tellTarget")
        if tellTarget and tellTarget ~= "" then
            return chatType, tellTarget
        end
    end

    if chatType == "SAY" or chatType == "YELL" or chatType == "PARTY" or chatType == "RAID" or chatType == "GUILD" or chatType == "OFFICER" then
        return chatType, nil
    end

    if IsInGuild() then
        return "GUILD", nil
    end

    return "SAY", nil
end

local function PostFact(category)
    local chatType, target = GetChatTarget()
    SendChatMessage(GetRandomFact(category), chatType, nil, target)
end

local function ShowHelp()
    local locale = GetLocale()
    local help = HELP_TEXT[locale] or HELP_TEXT["enUS"]
    for _, line in ipairs(help) do
        print(line)
    end

    local lang = FactorUselessDB and FactorUselessDB.language or GetLocale()
    local categories = {}
    for key in pairs(FACTS["enUS"]) do
        categories[#categories + 1] = key
    end
    table.sort(categories)
    if locale == "deDE" then
        print("  Aktuelle Sprache: |cff00ff00" .. lang .. "|r")
        print("  Kategorien: |cffffff00" .. table.concat(categories, ", ") .. "|r")
    else
        print("  Current language: |cff00ff00" .. lang .. "|r")
        print("  Categories: |cffffff00" .. table.concat(categories, ", ") .. "|r")
    end
end

local function SetLanguage(lang)
    local locale = GetLocale()

    if not lang or lang == "" then
        ShowHelp()
        return
    end

    lang = lang:match("^%s*(.-)%s*$")

    local SHORT_CODES = { en = "enUS", de = "deDE" }
    lang = SHORT_CODES[lang:lower()] or lang

    if not FACTS[lang] then
        if locale == "deDE" then
            print("|cff00ccffFactorUseless|r: Unbekannte Sprache: |cffff0000" .. lang .. "|r")
            print("Verfügbare Sprachen: |cffffff00" .. table.concat(AVAILABLE_LANGUAGES, ", ") .. "|r")
        else
            print("|cff00ccffFactorUseless|r: Unknown language: |cffff0000" .. lang .. "|r")
            print("Available languages: |cffffff00" .. table.concat(AVAILABLE_LANGUAGES, ", ") .. "|r")
        end
        return
    end

    FactorUselessDB.language = lang

    if locale == "deDE" then
        print("|cff00ccffFactorUseless|r: Sprache auf |cff00ff00" .. lang .. "|r gesetzt.")
    else
        print("|cff00ccffFactorUseless|r: Language set to |cff00ff00" .. lang .. "|r.")
    end
end

