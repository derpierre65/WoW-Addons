local AVAILABLE_LANGUAGES = { "enUS", "deDE" }

local HELP_TEXT = {
    enUS = {
        "|cff00ccffFactorUseless|r - Commands:",
        "  |cffffff00/fact|r - Show this help",
        "  |cffffff00/fact print|r - Post a random fact to chat",
        "  |cffffff00/fact language [enUS|deDE]|r - Set the language for facts",
    },
    deDE = {
        "|cff00ccffFactorUseless|r - Befehle:",
        "  |cffffff00/fact|r - Zeigt diese Hilfe an",
        "  |cffffff00/fact print|r - Postet einen zufälligen Fakt in den Chat",
        "  |cffffff00/fact language [enUS|deDE]|r - Stellt die Sprache für Fakten ein",
    },
}

local function GetRandomFact()
    local locale = FactorUselessDB and FactorUselessDB.language or GetLocale()
    local facts = FACTS[locale] or FACTS["enUS"]
    return facts[math.random(#facts)]
end

local function GetChatTarget()
    local chatType = ChatFrame1EditBox:GetAttribute("chatType")
    local channelTarget = ChatFrame1EditBox:GetAttribute("channelTarget")

    if chatType == "CHANNEL" and channelTarget then
        return chatType, channelTarget
    end

    if chatType == "WHISPER" then
        local tellTarget = ChatFrame1EditBox:GetAttribute("tellTarget")
        if tellTarget and tellTarget ~= "" then
            return chatType, tellTarget
        end
    end

    if chatType == "SAY" or chatType == "YELL" or chatType == "PARTY" or chatType == "RAID" or chatType == "GUILD" or chatType == "OFFICER" then
        return chatType, nil
    end

    if IsInGuild() then
        return "GUILD", nil
    end

    return "SAY", nil
end

local function PostFact()
    local chatType, target = GetChatTarget()
    SendChatMessage(GetRandomFact(), chatType, nil, target)
end

local function ShowHelp()
    local locale = GetLocale()
    local help = HELP_TEXT[locale] or HELP_TEXT["enUS"]
    for _, line in ipairs(help) do
        print(line)
    end

    local lang = FactorUselessDB and FactorUselessDB.language or GetLocale()
    if locale == "deDE" then
        print("  Aktuelle Sprache: |cff00ff00" .. lang .. "|r")
    else
        print("  Current language: |cff00ff00" .. lang .. "|r")
    end
end

local function SetLanguage(lang)
    local locale = GetLocale()

    if not lang or lang == "" then
        ShowHelp()
        return
    end

    lang = lang:match("^%s*(.-)%s*$")

    local SHORT_CODES = { en = "enUS", de = "deDE" }
    lang = SHORT_CODES[lang:lower()] or lang

    if not FACTS[lang] then
        if locale == "deDE" then
            print("|cff00ccffFactorUseless|r: Unbekannte Sprache: |cffff0000" .. lang .. "|r")
            print("Verfügbare Sprachen: |cffffff00" .. table.concat(AVAILABLE_LANGUAGES, ", ") .. "|r")
        else
            print("|cff00ccffFactorUseless|r: Unknown language: |cffff0000" .. lang .. "|r")
            print("Available languages: |cffffff00" .. table.concat(AVAILABLE_LANGUAGES, ", ") .. "|r")
        end
        return
    end

    FactorUselessDB.language = lang

    if locale == "deDE" then
        print("|cff00ccffFactorUseless|r: Sprache auf |cff00ff00" .. lang .. "|r gesetzt.")
    else
        print("|cff00ccffFactorUseless|r: Language set to |cff00ff00" .. lang .. "|r.")
    end
end

local frame = CreateFrame("Frame")
frame:RegisterEvent("PLAYER_ENTERING_WORLD")
frame:RegisterEvent("ADDON_LOADED")

local hasPosted = false

frame:SetScript("OnEvent", function(self, event, arg1)
    if event == "ADDON_LOADED" and arg1 == "FactorUseless" then
        FactorUselessDB = FactorUselessDB or {}
        if not FactorUselessDB.language then
            FactorUselessDB.language = GetLocale()
        end
    end

    if event == "PLAYER_ENTERING_WORLD" then
        if hasPosted then
            return
        end

        hasPosted = true

        -- Delay slightly to make sure guild chat is ready
        C_Timer.After(5, function()
            if IsInGuild() then
                SendChatMessage(GetRandomFact(), "GUILD")
            end
        end)
    end
end)

SLASH_FACTORUSELESS1 = "/fact"
SlashCmdList["FACTORUSELESS"] = function(msg)
    local command, rest = msg:match("^(%S+)%s*(.*)$")
    command = command and command:lower() or ""

    if command == "print" then
        PostFact()
    elseif command == "language" or command == "lang" then
        SetLanguage(rest)
    else
        ShowHelp()
    end
end
